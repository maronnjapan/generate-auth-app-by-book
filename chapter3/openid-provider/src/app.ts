/**
 * 生成した OpenID Provider（src/oidc-provider/）を Hono のアプリに組み込む。
 *
 * src/oidc-provider/ は `pnpm run generate`（maronn-oidc generate hono）が作る。
 * このファイルと server.ts は、生成コードを使う側として自分で持つ。
 * 認証認可の処理は生成コードと @maronn-openid-connect/core が担当し、
 * ここでは「設定」「署名鍵」「クライアントとユーザーの登録」だけを行う。
 */
import { Hono } from 'hono';
import { applyOidc } from './oidc-provider/apply.js';
import { createDatabase, registerClient } from './oidc-provider/db/index.js';
import { registerDevelopmentUsers } from './oidc-provider/development.js';
import { readSettings, type Environment } from './settings.js';
import { createEphemeralSigningKeyProvider } from './signing-key.js';

export async function createServerApp(env: Environment): Promise<Hono> {
  const settings = readSettings(env);

  // --db 無しで生成したので、データはこのプロセスのメモリに入る。
  // 起動のたびにクライアントとユーザーを登録する。
  const db = createDatabase();
  for (const client of settings.clients) {
    await registerClient(db, client);
  }
  // 検証用ユーザー testuser / otheruser（パスワードはどちらも password）。
  // 自分のユーザーを足すなら registerUser(db, { sub, name, email, password }) を呼ぶ。
  await registerDevelopmentUsers(db);

  const app = new Hono();
  app.get('/', (c) =>
    c.text(
      [
        'chapter3 OpenID Provider (generated by maronn-oidc)',
        `issuer: ${settings.issuer}`,
        `discovery: ${settings.issuer}/.well-known/openid-configuration`,
        `device verification: ${settings.issuer}/device`,
      ].join('\n'),
    ),
  );
  app.get('/health', (c) => c.json({ status: 'ok' }));

  applyOidc(app, {
    config: { issuer: settings.issuer },
    signingKeyProvider: createEphemeralSigningKeyProvider(env['OIDC_SIGNING_KEY_ID'] ?? 'chapter3-rs256-key'),
    corsOrigins: settings.issuer,
  });

  return app;
}
